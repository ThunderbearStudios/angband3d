#!/usr/bin/env node
/**
 * tools/build_worker_cartridges.js
 *
 * Bundles the 5 Yendor 3D JS Cartridges (NetHack, DCSS, Brogue, Rogue, RYOD)
 * plus UniversalCartridgeEngine, RyodCompiler, RealmContentPool, a Uint8Array
 * Buffer shim, and an IndexedDB-backed `/lib/save` Virtual File System into
 * `server/public/js/cartridges-worker-bundle.js` for 0ms offline execution inside
 * `engine-worker.js`.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'server/public/js/cartridges-worker-bundle.js');

const MODULES = [
    { id: '/public/js/realm-content-pool.js', rel: 'server/public/js/realm-content-pool.js' },
    { id: '/public/js/ryod-compiler.js', rel: 'server/public/js/ryod-compiler.js' },
    { id: '/server/src/cartridges/realm-content-pool.js', alias: '/public/js/realm-content-pool.js' },
    { id: '/server/src/cartridges/ryod-compiler.js', alias: '/public/js/ryod-compiler.js' },
    { id: '/server/src/cartridges/ryod-systems.js', rel: 'server/src/cartridges/ryod-systems.js', optional: true },
    { id: '/server/src/cartridges/cartridge-core.js', rel: 'server/src/cartridges/cartridge-core.js' },
    { id: '/variants/nethack/bin/nethack-bridge.js', rel: 'variants/nethack/bin/nethack-bridge.js' },
    { id: '/variants/dcss/bin/dcss-bridge.js', rel: 'variants/dcss/bin/dcss-bridge.js' },
    { id: '/variants/brogue/bin/brogue-bridge.js', rel: 'variants/brogue/bin/brogue-bridge.js' },
    { id: '/variants/rogue/bin/rogue-bridge.js', rel: 'variants/rogue/bin/rogue-bridge.js' },
    { id: '/variants/ryod/bin/ryod-bridge.js', rel: 'variants/ryod/bin/ryod-bridge.js' }
];

function stripShebang(src) {
    return src.replace(/^#!.*\r?\n/, '');
}

const moduleEntries = [];
for (const m of MODULES) {
    if (m.alias) {
        moduleEntries.push(
            `    ${JSON.stringify(m.id)}: function(module, exports, require) {\n` +
            `        module.exports = require(${JSON.stringify(m.alias)});\n` +
            `    }`
        );
        continue;
    }
    const fullPath = path.join(ROOT, m.rel);
    if (m.optional && !fs.existsSync(fullPath)) continue;
    const code = stripShebang(fs.readFileSync(fullPath, 'utf8'));
    const dir = path.posix.dirname(m.id);
    moduleEntries.push(
        `    ${JSON.stringify(m.id)}: function(module, exports, require, __filename, __dirname, Buffer, process) {\n` +
        `${code}\n` +
        `    }`
    );
}

const bundleSource = `/**
 * AUTO-GENERATED BY tools/build_worker_cartridges.js — DO NOT EDIT DIRECTLY.
 * Yendor 3D Browser-Worker Cartridge Runtime (nethack, dcss, brogue, rogue, ryod).
 */
/* eslint-disable */
(function (globalObj) {
    'use strict';

    const utf8Enc = (typeof TextEncoder !== 'undefined') ? new TextEncoder() : null;
    const utf8Dec = (typeof TextDecoder !== 'undefined') ? new TextDecoder('utf-8') : null;

    class WorkerBuffer extends Uint8Array {
        static isBuffer(b) { return b instanceof WorkerBuffer || (typeof Buffer !== 'undefined' && Buffer.isBuffer(b)); }
        static alloc(size, fill = 0) {
            const b = new WorkerBuffer(size >>> 0);
            if (fill) b.fill(fill & 0xff);
            return b;
        }
        static from(input, encoding = 'utf8') {
            if (typeof input === 'string') {
                if (encoding === 'ascii' || !utf8Enc) {
                    const b = new WorkerBuffer(input.length);
                    for (let i = 0; i < input.length; i++) b[i] = input.charCodeAt(i) & 0x7f;
                    return b;
                }
                const bytes = utf8Enc.encode(input);
                const b = new WorkerBuffer(bytes.length);
                b.set(bytes);
                return b;
            }
            if (input instanceof ArrayBuffer) return new WorkerBuffer(new Uint8Array(input));
            if (ArrayBuffer.isView(input)) {
                const b = new WorkerBuffer(input.byteLength);
                b.set(new Uint8Array(input.buffer, input.byteOffset, input.byteLength));
                return b;
            }
            if (Array.isArray(input)) {
                const b = new WorkerBuffer(input.length);
                for (let i = 0; i < input.length; i++) b[i] = input[i] & 0xff;
                return b;
            }
            return new WorkerBuffer(0);
        }
        static concat(list, totalLength) {
            const total = (typeof totalLength === 'number')
                ? totalLength
                : list.reduce((acc, item) => acc + (item ? item.length : 0), 0);
            const out = new WorkerBuffer(total);
            let offset = 0;
            for (const item of list) {
                if (!item || !item.length) continue;
                const len = Math.min(item.length, total - offset);
                if (len <= 0) break;
                out.set(item.subarray(0, len), offset);
                offset += len;
            }
            return out;
        }
        write(str, offset = 0, length, encoding = 'utf8') {
            const s = String(str || '');
            const maxLen = (typeof length === 'number') ? Math.min(length, this.length - offset) : (this.length - offset);
            if (maxLen <= 0) return 0;
            const src = WorkerBuffer.from(s, encoding);
            const n = Math.min(src.length, maxLen);
            this.set(src.subarray(0, n), offset);
            return n;
        }
        writeUInt32LE(value, offset = 0) {
            const v = value >>> 0;
            this[offset] = v & 0xff;
            this[offset + 1] = (v >>> 8) & 0xff;
            this[offset + 2] = (v >>> 16) & 0xff;
            this[offset + 3] = (v >>> 24) & 0xff;
            return offset + 4;
        }
        readUInt32LE(offset = 0) {
            return ((this[offset]) | (this[offset + 1] << 8) | (this[offset + 2] << 16) | (this[offset + 3] * 0x1000000)) >>> 0;
        }
        toString(encoding = 'utf8', start = 0, end = this.length) {
            const sub = this.subarray(Math.max(0, start), Math.min(this.length, end));
            if (encoding === 'ascii' || !utf8Dec) {
                let s = '';
                for (let i = 0; i < sub.length; i++) s += String.fromCharCode(sub[i]);
                return s;
            }
            return utf8Dec.decode(sub);
        }
    }

    const BufferShim = (typeof Buffer !== 'undefined') ? Buffer : WorkerBuffer;

    function normPath(p) {
        const raw = String(p || '/').replace(/\\\\/g, '/');
        const parts = raw.split('/');
        const out = [];
        for (const seg of parts) {
            if (!seg || seg === '.') continue;
            if (seg === '..') out.pop();
            else out.push(seg);
        }
        return '/' + out.join('/');
    }

    const pathShim = {
        join: (...args) => normPath(args.filter(Boolean).join('/')),
        resolve: (...args) => {
            let acc = '';
            for (const a of args) {
                const s = String(a || '').replace(/\\\\/g, '/');
                if (!s) continue;
                acc = s.startsWith('/') ? s : (acc ? acc + '/' + s : s);
            }
            return normPath(acc || '/');
        },
        dirname: (p) => {
            const n = normPath(p);
            const idx = n.lastIndexOf('/');
            return idx <= 0 ? '/' : n.slice(0, idx);
        },
        basename: (p) => {
            const n = normPath(p);
            const idx = n.lastIndexOf('/');
            return idx < 0 ? n : n.slice(idx + 1);
        }
    };

    const VFS = {
        DB_NAME: '/lib/save',
        STORE_NAME: 'FILE_DATA',
        DB_VERSION: 22,
        files: new Map(),
        dirty: new Set(),
        deleted: new Set(),
        _hydrated: false,

        existsSync(p) {
            const np = normPath(p);
            if (np === '/' || np === '/lib' || np === '/lib/save') return true;
            return this.files.has(np);
        },
        mkdirSync() { return true; },
        writeFileSync(p, data) {
            const np = normPath(p);
            const bytes = (typeof data === 'string') ? BufferShim.from(data, 'utf8') : BufferShim.from(data);
            this.files.set(np, bytes);
            this.deleted.delete(np);
            if (np.startsWith('/lib/save/')) this.dirty.add(np);
        },
        readFileSync(p, enc) {
            const np = normPath(p);
            if (!this.files.has(np)) throw new Error('ENOENT: ' + np);
            const buf = BufferShim.from(this.files.get(np));
            return enc ? buf.toString(enc) : buf;
        },
        copyFileSync(src, dst) {
            const buf = this.readFileSync(src);
            this.writeFileSync(dst, buf);
        },
        unlinkSync(p) {
            const np = normPath(p);
            this.files.delete(np);
            this.dirty.delete(np);
            if (np.startsWith('/lib/save/')) this.deleted.add(np);
        },
        readdirSync(dir) {
            const prefix = normPath(dir).replace(/\\/$/, '') + '/';
            const out = [];
            for (const k of this.files.keys()) {
                if (k.startsWith(prefix)) {
                    const rest = k.slice(prefix.length);
                    if (rest && !rest.includes('/')) out.push(rest);
                }
            }
            return out;
        },
        openDB() {
            return new Promise((resolve) => {
                if (typeof indexedDB === 'undefined') return resolve(null);
                const req = indexedDB.open(this.DB_NAME, this.DB_VERSION);
                req.onupgradeneeded = (e) => {
                    const db = e.target.result;
                    const store = db.objectStoreNames.contains(this.STORE_NAME)
                        ? e.target.transaction.objectStore(this.STORE_NAME)
                        : db.createObjectStore(this.STORE_NAME);
                    if (store && !store.indexNames.contains('timestamp')) {
                        store.createIndex('timestamp', 'timestamp', { unique: false });
                    }
                };
                req.onsuccess = () => resolve(req.result);
                req.onerror = () => resolve(null);
            });
        },
        async hydrateFromIndexedDB() {
            const db = await this.openDB();
            if (!db) { this._hydrated = true; return false; }
            return new Promise((resolve) => {
                try {
                    const tx = db.transaction(this.STORE_NAME, 'readonly');
                    const store = tx.objectStore(this.STORE_NAME);
                    const req = store.openCursor();
                    req.onsuccess = (ev) => {
                        const cursor = ev.target.result;
                        if (cursor) {
                            const key = String(cursor.key || '');
                            const val = cursor.value;
                            if (key.startsWith('/lib/save/') && val && val.contents) {
                                this.files.set(normPath(key), BufferShim.from(val.contents));
                            }
                            cursor.continue();
                        } else {
                            this._hydrated = true;
                            resolve(true);
                        }
                    };
                    req.onerror = () => { this._hydrated = true; resolve(false); };
                } catch (_) {
                    this._hydrated = true;
                    resolve(false);
                }
            });
        },
        async flushToIndexedDB() {
            if (this.dirty.size === 0 && this.deleted.size === 0) return true;
            const db = await this.openDB();
            if (!db) return false;
            const toWrite = Array.from(this.dirty);
            const toDel = Array.from(this.deleted);
            this.dirty.clear();
            this.deleted.clear();
            return new Promise((resolve) => {
                try {
                    const tx = db.transaction(this.STORE_NAME, 'readwrite');
                    const store = tx.objectStore(this.STORE_NAME);
                    const now = new Date();
                    for (const k of toWrite) {
                        const bytes = this.files.get(k);
                        if (bytes) {
                            store.put({ timestamp: now, mode: 33206, contents: new Uint8Array(bytes) }, k);
                        }
                    }
                    for (const k of toDel) store.delete(k);
                    tx.oncomplete = () => resolve(true);
                    tx.onerror = () => resolve(false);
                } catch (_) {
                    resolve(false);
                }
            });
        }
    };

    const cryptoShim = {
        randomBytes(size) {
            const u = new Uint8Array(size >>> 0);
            if (globalObj.crypto && typeof globalObj.crypto.getRandomValues === 'function') {
                globalObj.crypto.getRandomValues(u);
            } else {
                for (let i = 0; i < u.length; i++) u[i] = (Math.random() * 256) | 0;
            }
            return BufferShim.from(u);
        }
    };

    const readlineShim = {
        createInterface() { return { on() {}, close() {} }; }
    };

    const processShim = {
        argv: ['node', 'worker-cartridge'],
        env: {},
        stdout: { write() {} },
        stdin: {},
        exit() {}
    };

    const MODULE_FACTORIES = {
${moduleEntries.join(',\n')}
    };

    const moduleCache = new Map();

    function makeRequire(fromDir) {
        function req(specifier) {
            if (specifier === 'fs') return VFS;
            if (specifier === 'path') return pathShim;
            if (specifier === 'crypto') return cryptoShim;
            if (specifier === 'readline') return readlineShim;
            let resolved = specifier.startsWith('.')
                ? pathShim.resolve(fromDir, specifier)
                : normPath(specifier);
            if (!MODULE_FACTORIES[resolved] && MODULE_FACTORIES[resolved + '.js']) {
                resolved = resolved + '.js';
            }
            if (moduleCache.has(resolved)) return moduleCache.get(resolved).exports;
            const factory = MODULE_FACTORIES[resolved];
            if (!factory) throw new Error('Worker bundle missing module: ' + specifier + ' (resolved ' + resolved + ')');
            const mod = { id: resolved, exports: {} };
            moduleCache.set(resolved, mod);
            factory(mod, mod.exports, makeRequire(pathShim.dirname(resolved)), resolved, pathShim.dirname(resolved), BufferShim, processShim);
            return mod.exports;
        }
        req.main = null;
        return req;
    }

    const rootRequire = makeRequire('/');

    const VERB_BITS = [
        'quaff', 'read', 'eat', 'aim', 'use_staff', 'zap', 'activate', 'fire',
        'throw', 'wield', 'takeoff', 'drop', 'inscribe', 'uninscribe', 'refill',
        'browse', 'study', 'cast', 'ignore', 'examine'
    ];

    function splitKeysSequence(arg) {
        const s = String(arg || '');
        if (!s) return [];
        if (/^(up|down|left|right|home|end|pageup|pagedown|enter|return|escape|esc|space|tab|backspace|delete)$/i.test(s)) {
            return [s];
        }
        if (s.length === 1) return [s];
        return s.split('');
    }

    function createCartridgeSession(opts = {}) {
        const realm = String(opts.realm || 'rogue').toLowerCase();
        const saveDir = opts.saveDir || '/lib/save';
        const rawUser = String(opts.saveFile || opts.user || 'Adventurer').trim().replace(/^\\/lib\\/save\\//, '').replace(/\\.sav$/i, '');
        const cleanUser = rawUser.replace(/[^a-zA-Z0-9_.-]/g, '_') || 'Adventurer';
        const cliOpts = {
            saveDir,
            user: cleanUser,
            isNew: Boolean(opts.isNew),
            customBirth: Boolean(opts.customBirth),
            randomBirth: Boolean(opts.randomBirth),
            args: opts.randomBirth ? ['-r'] : [],
            seed: opts.seed !== undefined ? opts.seed : undefined,
            ryodBlueprint: opts.ryodBlueprint || null
        };

        if (realm === 'ryod' && opts.ryodBlueprint && typeof opts.ryodBlueprint === 'object') {
            VFS.writeFileSync(pathShim.join(saveDir, cleanUser + '.ryod.json'), JSON.stringify(opts.ryodBlueprint));
        }

        let engine = null;
        let version = '1.0.0-bridge';
        if (realm === 'nethack') {
            const { NetHackEngine } = rootRequire('/variants/nethack/bin/nethack-bridge.js');
            engine = new NetHackEngine(cliOpts);
            version = '3.6.7-bridge';
        } else if (realm === 'dcss') {
            const { DCSSEngine, DCSS_SPEC } = rootRequire('/variants/dcss/bin/dcss-bridge.js');
            engine = new DCSSEngine(cliOpts);
            version = DCSS_SPEC.version || '0.32-bridge';
        } else if (realm === 'brogue') {
            const { BrogueEngine, BROGUE_SPEC } = rootRequire('/variants/brogue/bin/brogue-bridge.js');
            engine = new BrogueEngine(cliOpts);
            version = BROGUE_SPEC.version || '1.14-ce-bridge';
        } else if (realm === 'rogue') {
            const { RogueEngine, ROGUE_SPEC } = rootRequire('/variants/rogue/bin/rogue-bridge.js');
            engine = new RogueEngine(cliOpts);
            version = ROGUE_SPEC.version || '5.4.4-bridge';
        } else if (realm === 'ryod') {
            const { RyodEngine } = rootRequire('/variants/ryod/bin/ryod-bridge.js');
            engine = new RyodEngine(cliOpts);
            version = (engine.spec && engine.spec.version) || '2.0.0-ryod';
        } else {
            throw new Error('Unsupported worker cartridge realm: ' + realm);
        }

        return {
            realm,
            user: cleanUser,
            engine,
            getHello() {
                return {
                    t: 'hello',
                    protocol: 1,
                    protocol_minor: 2,
                    version,
                    realm,
                    savefile: engine.saveFile
                };
            },
            getCommands() {
                return { t: 'commands', realm, verbBits: VERB_BITS.slice() };
            },
            getFrame() {
                return engine.buildFrame();
            },
            handleCommand(rawCmd) {
                const line = String(rawCmd || '').trim();
                if (!line) return [];
                if (line === 'save') {
                    const ok = engine.saveGame();
                    return [{ t: 'ok', detail: 'saved', ok: ok !== false }];
                }
                if (line === 'frame') {
                    return [engine.buildFrame()];
                }
                if (line === 'quit' || line === 'exit') {
                    engine.saveGame();
                    return [{ t: 'bye', detail: 'Game session saved and closed' }];
                }
                if (line.startsWith('keys ')) {
                    const keys = splitKeysSequence(line.slice(5));
                    for (const k of keys) engine.handleKey(k);
                    return [engine.buildFrame()];
                }
                if (line.startsWith('key ')) {
                    engine.handleKey(line.slice(4));
                    return [engine.buildFrame()];
                }
                return [];
            }
        };
    }

    const exported = {
        SUPPORTED_CARTRIDGES: ['nethack', 'dcss', 'brogue', 'rogue', 'ryod'],
        VFS,
        BufferShim,
        createCartridgeSession
    };

    globalObj.YendorWorkerCartridges = exported;
    if (typeof module === 'object' && module.exports) {
        module.exports = exported;
    }
})(typeof self !== 'undefined' ? self : globalThis);
`;

const OUT_FILE1 = path.join(ROOT, 'server/public/js/cartridges-worker-bundle.js');
const OUT_FILE2 = path.join(ROOT, 'server/public/js/worker-cartridges.js');

fs.writeFileSync(OUT_FILE1, bundleSource, 'utf8');
fs.writeFileSync(OUT_FILE2, bundleSource, 'utf8');
const stat1 = fs.statSync(OUT_FILE1);
const stat2 = fs.statSync(OUT_FILE2);
console.log(`[build_worker_cartridges] Wrote ${path.relative(ROOT, OUT_FILE1)} (${(stat1.size / 1024).toFixed(1)} KB) and ${path.relative(ROOT, OUT_FILE2)} (${(stat2.size / 1024).toFixed(1)} KB)`);
