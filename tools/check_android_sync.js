#!/usr/bin/env node
'use strict';

/**
 * WS10.1: Android asset drift verification.
 * Compares SHA-1 hashes of all files in server/public with android/app/src/main/assets/public.
 * Exits 0 on match, 1 on any mismatch or missing file.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const assert = require('assert');

const rootDir = path.join(__dirname, '..');
const webDir = path.join(rootDir, 'server', 'public');
const androidDir = path.join(rootDir, 'android', 'app', 'src', 'main', 'assets', 'public');

if (!fs.existsSync(androidDir)) {
    console.log('SKIP: Android assets dir does not exist (generated by Capacitor; not tracked in git)');
    process.exit(0);
}

console.log('Testing Android asset sync (WS10.1)...');
console.log(`  Web assets source:    ${webDir}`);
console.log(`  Android asset target: ${androidDir}`);

if (!fs.existsSync(webDir)) {
    console.error(`ERROR: Web dir does not exist: ${webDir}`);
    process.exit(1);
}

function getSha1(filePath) {
    const data = fs.readFileSync(filePath);
    return crypto.createHash('sha1').update(data).digest('hex');
}

function walkDir(dir, baseDir = dir) {
    let files = [];
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            files = files.concat(walkDir(fullPath, baseDir));
        } else if (entry.isFile()) {
            const relPath = path.relative(baseDir, fullPath).replace(/\\/g, '/');
            files.push(relPath);
        }
    }
    return files;
}

// WS12: Bloat elimination for mobile APK packaging:
// Web-marketing demo video frames (107.7MB) and demo.html are desktop/web showcases
// and must NOT be packaged inside the mobile APK.
const EXCLUDED_ANDROID_PREFIXES = [
    'assets/video',
    'demo.html'
];

function isExcludedFromAndroid(relPath) {
    const norm = relPath.replace(/\\/g, '/');
    return EXCLUDED_ANDROID_PREFIXES.some(prefix => norm === prefix || norm.startsWith(prefix + '/'));
}

const webFiles = walkDir(webDir);
let mismatches = 0;
let missingInAndroid = 0;
let prunedBloatCount = 0;
let bloatViolations = 0;

for (const relPath of webFiles) {
    const androidFile = path.join(androidDir, relPath);
    if (isExcludedFromAndroid(relPath)) {
        if (fs.existsSync(androidFile)) {
            console.error(`  BLOAT DETECTED in Android assets: ${relPath} should not be packaged in APK!`);
            bloatViolations++;
        } else {
            prunedBloatCount++;
        }
        continue;
    }

    if (!fs.existsSync(androidFile)) {
        console.error(`  MISSING in Android: ${relPath}`);
        missingInAndroid++;
        continue;
    }

    const webFile = path.join(webDir, relPath);
    const webHash = getSha1(webFile);
    const androidHash = getSha1(androidFile);

    if (webHash !== androidHash) {
        console.error(`  HASH MISMATCH: ${relPath} (web: ${webHash.slice(0, 8)}, android: ${androidHash.slice(0, 8)})`);
        mismatches++;
    }
}

console.log(`\nChecked ${webFiles.length} files:`);
console.log(`  - Mismatches:     ${mismatches}`);
console.log(`  - Missing:        ${missingInAndroid}`);
console.log(`  - Pruned Bloat:   ${prunedBloatCount} files (>107MB saved)`);
console.log(`  - Bloat Leaks:    ${bloatViolations}`);

if (mismatches > 0 || missingInAndroid > 0 || bloatViolations > 0) {
    console.error('\n❌ Android assets validation failed!');
    process.exit(1);
}

console.log('\n✓ All Android game assets match server/public exactly, and bloat is cleanly pruned!');
process.exit(0);
